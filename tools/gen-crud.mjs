// Generates view + CRUD functions for every entity in entities.mjs.
//   node LearnDB/tools/gen-crud.mjs
// Output: LearnDB/functions/generated/<key>.sql  (idempotent; safe to re-run)
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { entities } from './entities.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = join(here, '..', 'functions', 'generated')
mkdirSync(outDir, { recursive: true })

const S = 'learninsurancedb'
const cast = {
  text: (k) => `NULLIF(p_data->>'${k}', '')`,
  int: (k) => `NULLIF(p_data->>'${k}', '')::int`,
  bigint: (k) => `NULLIF(p_data->>'${k}', '')::bigint`,
  numeric: (k) => `NULLIF(p_data->>'${k}', '')::numeric`,
  bool: (k) => `COALESCE(NULLIF(p_data->>'${k}', '')::boolean, FALSE)`,
  boolnull: (k) => `NULLIF(p_data->>'${k}', '')::boolean`,
  date: (k) => `NULLIF(p_data->>'${k}', '')::date`,
  timestamptz: (k) => `NULLIF(p_data->>'${k}', '')::timestamptz`,
  jsonb: (k) => `NULLIF(p_data->'${k}', 'null'::jsonb)`,
}
const snake = (s) => s.replace(/[A-Z]/g, (c) => '_' + c.toLowerCase())

const valueExpr = (c) => (c.def ? `COALESCE(${cast[c.type](c.json)}, ${c.def})` : cast[c.type](c.json))

for (const e of entities) {
  const skip = new Set(e.skip ?? [])
  const cols = e.columns.map(([col, json, type = 'text', def]) => ({ col, json, type, def }))
  const view = `vw_${e.table}`
  const fn = (action) => `${S}.fn_${e.key}_${action}`
  const sortable = [...new Set([...cols.map((c) => c.col), 'id', 'created_date', 'modified_date', 'is_active', ...(e.sortExtra ?? [])])]
  const filterCols = [...new Set(['is_active', ...(e.filters ?? [])])]
  const label = e.label ?? e.key
  const defaultSort = e.defaultSort ?? 'created_date'
  const defaultDir = e.defaultDir ?? 'DESC'
  const searchSql = (e.search ?? []).map((c) => `${c}::text ILIKE %1$L`).join(' OR ')

  const sql = `-- GENERATED by LearnDB/tools/gen-crud.mjs from entities.mjs - do not edit by hand.
-- Entity: ${e.key} (table ${e.table})

DROP VIEW IF EXISTS ${S}.${view} CASCADE;
CREATE VIEW ${S}.${view} AS
${e.view ?? `SELECT t.*${e.extraSelect ? ',\n       ' + e.extraSelect : ''}
FROM ${S}.${e.table} t${e.joins ? '\n' + e.joins : ''}`};

-- LIST: search + filters + sort + paging. Returns { items, totalCount, page, pageSize }
DROP FUNCTION IF EXISTS ${fn('get_all')}(text, int, int, text, text, jsonb);
CREATE FUNCTION ${fn('get_all')}(
    p_search    text  DEFAULT NULL,
    p_page      int   DEFAULT 1,
    p_page_size int   DEFAULT 10,
    p_sort_by   text  DEFAULT NULL,
    p_sort_dir  text  DEFAULT NULL,
    p_filters   jsonb DEFAULT '{}'::jsonb
) RETURNS jsonb
LANGUAGE plpgsql STABLE AS $fn$
DECLARE
    v_page   int := GREATEST(COALESCE(p_page, 1), 1);
    v_size   int := LEAST(GREATEST(COALESCE(p_page_size, 10), 1), 500);
    v_sort   text := ${S}.fn_to_snake(p_sort_by);
    v_dir    text := CASE WHEN lower(COALESCE(p_sort_dir, '${defaultDir}')) = 'asc' THEN 'ASC' ELSE 'DESC' END;
    v_where  text := 'WHERE TRUE';
    v_like   text;
    v_key    text;
    v_val    text;
    v_col    text;
    v_total  bigint;
    v_items  jsonb;
BEGIN
    IF v_sort IS NULL OR NOT (v_sort = ANY (ARRAY[${sortable.map((c) => `'${c}'`).join(', ')}])) THEN
        v_sort := '${defaultSort}';
        IF p_sort_by IS NULL THEN v_dir := '${defaultDir}'; END IF;
    END IF;
${
    searchSql
      ? `
    IF p_search IS NOT NULL AND btrim(p_search) <> '' THEN
        v_like := '%' || btrim(p_search) || '%';
        v_where := v_where || format(' AND (${searchSql})', v_like);
    END IF;
`
      : ''
  }
    FOR v_key, v_val IN SELECT key, value FROM jsonb_each_text(COALESCE(p_filters, '{}'::jsonb)) LOOP
        v_col := ${S}.fn_to_snake(v_key);
        IF v_col = ANY (ARRAY[${filterCols.map((c) => `'${c}'`).join(', ')}]) AND COALESCE(v_val, '') <> '' THEN
            v_where := v_where || format(' AND %I::text = %L', v_col, v_val);
        END IF;
    END LOOP;
${e.extraWhere ? `\n    ${e.extraWhere}\n` : ''}
    EXECUTE format('SELECT count(*) FROM ${S}.${view} %s', v_where) INTO v_total;
    EXECUTE format(
        'SELECT COALESCE(jsonb_agg(${S}.fn_to_camel(to_jsonb(q))), ''[]''::jsonb)
         FROM (SELECT * FROM ${S}.${view} %s ORDER BY %I %s, id DESC LIMIT %s OFFSET %s) q',
        v_where, v_sort, v_dir, v_size, (v_page - 1) * v_size) INTO v_items;

    RETURN jsonb_build_object('items', v_items, 'totalCount', v_total, 'page', v_page, 'pageSize', v_size);
END
$fn$;

-- GET BY ID: returns the row as JSON, or NULL when not found
CREATE OR REPLACE FUNCTION ${fn('get_by_id')}(p_id bigint) RETURNS jsonb
LANGUAGE sql STABLE AS $fn$
    SELECT ${S}.fn_to_camel(to_jsonb(v)) FROM ${S}.${view} v WHERE v.id = p_id;
$fn$;

${skip.has('create') ? '' : `-- CREATE: p_data uses camelCase keys
CREATE OR REPLACE FUNCTION ${fn('create')}(p_data jsonb, p_user text DEFAULT 'system') RETURNS jsonb
LANGUAGE plpgsql AS $fn$
DECLARE v_id bigint;
BEGIN
    INSERT INTO ${S}.${e.table} (${cols.map((c) => c.col).join(', ')}, created_by)
    VALUES (${cols.map(valueExpr).join(',\n            ')},
            COALESCE(p_user, 'system'))
    RETURNING id INTO v_id;
    RETURN ${fn('get_by_id')}(v_id);
END
$fn$;
`}

${skip.has('update') ? '' : `-- UPDATE: only keys present in p_data are changed (so partial and full updates both work)
CREATE OR REPLACE FUNCTION ${fn('update')}(p_id bigint, p_data jsonb, p_user text DEFAULT 'system') RETURNS jsonb
LANGUAGE plpgsql AS $fn$
BEGIN
    UPDATE ${S}.${e.table} SET
        ${cols.map((c) => `${c.col} = CASE WHEN p_data ? '${c.json}' THEN ${valueExpr(c)} ELSE ${c.col} END`).join(',\n        ')},
        modified_date = now(),
        modified_by = COALESCE(p_user, 'system')
    WHERE id = p_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION '${label} % not found', p_id USING ERRCODE = 'P0002';
    END IF;
    RETURN ${fn('get_by_id')}(p_id);
END
$fn$;
`}

-- SET ACTIVE: soft delete / restore
CREATE OR REPLACE FUNCTION ${fn('set_active')}(p_id bigint, p_active boolean, p_user text DEFAULT 'system') RETURNS jsonb
LANGUAGE plpgsql AS $fn$
BEGIN
    UPDATE ${S}.${e.table} SET is_active = p_active, modified_date = now(), modified_by = COALESCE(p_user, 'system')
    WHERE id = p_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION '${label} % not found', p_id USING ERRCODE = 'P0002';
    END IF;
    RETURN ${fn('get_by_id')}(p_id);
END
$fn$;

-- DELETE (soft): sets is_active = false
CREATE OR REPLACE FUNCTION ${fn('delete')}(p_id bigint, p_user text DEFAULT 'system') RETURNS jsonb
LANGUAGE plpgsql AS $fn$
BEGIN
    PERFORM ${fn('set_active')}(p_id, FALSE, p_user);
    RETURN jsonb_build_object('id', p_id, 'deleted', TRUE);
END
$fn$;
`
  writeFileSync(join(outDir, `${e.key}.sql`), sql)
  console.log('generated', e.key)
}

